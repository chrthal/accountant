-- Phase 3: imported bank transactions (ADR 0009). Keep in lockstep with
-- sqlite/0004_bank.sql.
--
-- A bank transaction is evidence that money moved, not a booking. Its content
-- is immutable; only its link to a ledger entry can be made and unmade, which
-- is why this table has no append-only trigger on matched_entry_id.

CREATE TABLE bank_transactions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booked_on        TEXT NOT NULL,          -- 'YYYY-MM-DD'
    amount_cents     BIGINT NOT NULL,        -- signed: negative left the account
    counterparty     TEXT NOT NULL DEFAULT '',
    purpose          TEXT NOT NULL DEFAULT '',
    -- Hash of the source row: re-importing the same export, or an overlapping
    -- date range, must not double a transaction.
    row_hash         TEXT NOT NULL UNIQUE,
    source_name      TEXT NOT NULL DEFAULT '',
    imported_at      TIMESTAMP NOT NULL,
    matched_entry_id BIGINT UNIQUE REFERENCES entries (id)
);

CREATE INDEX bank_transactions_booked_on_idx ON bank_transactions (booked_on);
CREATE INDEX bank_transactions_matched_idx   ON bank_transactions (matched_entry_id);
